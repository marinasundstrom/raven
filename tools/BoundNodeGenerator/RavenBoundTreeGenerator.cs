using System.Text;

namespace BoundNodeGenerator;

static class RavenBoundTreeGenerator
{
    private static string ParameterName(ParameterModel parameter) => "@" + parameter.ParameterName.TrimStart('@');

    public static string Generate(IReadOnlyList<BoundNodeModel> models, IEnumerable<string> portedNames)
    {
        var byName = models.ToDictionary(node => node.Name, StringComparer.Ordinal);
        var nodes = portedNames.Select(name => byName[name]).OrderBy(node => node.Name, StringComparer.Ordinal).ToArray();
        var builder = new StringBuilder("// <auto-generated />").AppendLine()
            .AppendLine("namespace Raven.CodeAnalysis").AppendLine()
            .AppendLine("import System.Collections.Immutable.*");
        foreach (var generic in new[] { false, true })
        {
            var suffix = generic ? "<TResult>" : "";
            var result = generic ? " -> TResult" : "";
            builder.AppendLine().AppendLine($"internal open partial class BoundTreeVisitor{suffix} {{");
            foreach (var category in new[] { "Statement", "Expression", "Pattern", "Designator" })
            {
                builder.AppendLine($"    virtual func Visit{category}(node: Bound{category}){result} {{");
                foreach (var node in nodes)
                {
                    var parent = node.BaseTypeName;
                    while (parent is not null && parent is not ("BoundStatement" or "BoundExpression" or "BoundPattern" or "BoundDesignator"))
                        parent = byName.TryGetValue(parent, out var ancestor) ? ancestor.BaseTypeName : null;
                    if (parent != "Bound" + category)
                        continue;

                    var variable = NameHelpers.ToCamelCase(node.Name);
                    builder.AppendLine($"        if node is {node.Name} {variable} {{");
                    builder.AppendLine($"            {(generic ? "return " : "")}Visit{node.VisitorMethodName}({variable})");
                    if (!generic)
                        builder.AppendLine("            return");
                    builder.AppendLine("        }");
                }
                builder.AppendLine($"        {(generic ? "return " : "")}DefaultVisit(node)").AppendLine("    }").AppendLine();
            }
            foreach (var node in nodes)
                builder.AppendLine($"    virtual func Visit{node.VisitorMethodName}(node: {node.Name}){result} => DefaultVisit(node)").AppendLine();
            builder.AppendLine("}");
        }

        foreach (var node in nodes.Where(node => node.IsPartial))
        {
            builder.AppendLine().AppendLine($"internal partial class {node.Name} {{");
            builder.AppendLine($"    override func Accept(visitor: BoundTreeVisitor) => visitor.Visit{node.VisitorMethodName}(self)").AppendLine();
            builder.AppendLine($"    override func Accept<TResult>(visitor: BoundTreeVisitor<TResult>) -> TResult => visitor.Visit{node.VisitorMethodName}(self)");
            if (node.HasUpdate)
            {
                var parameters = string.Join(", ", node.Parameters.Select(p => $"{ParameterName(p)}: {p.TypeName}"));
                var changed = string.Join(" || ", node.Parameters.Select(p =>
                    p.Kind is ParameterKind.Symbol or ParameterKind.BoundNode || p.NonNullableTypeName == "object"
                        ? $"!object.ReferenceEquals(self.{p.PropertyName}, {ParameterName(p)})"
                        : $"self.{p.PropertyName} != {ParameterName(p)}"));
                var arguments = string.Join(", ", node.Parameters.Select(ParameterName));
                builder.AppendLine().AppendLine($"    internal func Update({parameters}) -> {node.Name} {{")
                    .AppendLine($"        if {changed} {{").AppendLine($"            return {node.Name}({arguments})")
                    .AppendLine("        }").AppendLine("        return self").AppendLine("    }");
            }
            builder.AppendLine("}");
        }
        return builder.ToString();
    }
}
