using System.Text;

namespace Raven.Generators;

internal static partial class DiagnosticDescriptorGenerator
{
    public static string GenerateRavenDiagnosticBagExtensions(List<DiagnosticDescriptorModel> diagnostics)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("// This file was generated by tools/DiagnosticsGenerator.");
        builder.AppendLine();
        builder.AppendLine("namespace Raven.CodeAnalysis");
        builder.AppendLine();
        builder.AppendLine("import System.Runtime.CompilerServices.*");
        builder.AppendLine();
        builder.AppendLine("public static partial class DiagnosticBagExtensions {");
        foreach (var diagnostic in diagnostics)
        {
            var parameters = diagnostic.Arguments.Select(argument => $"@{argument}: object?")
                .Prepend("diagnostics: DiagnosticBag").Append("location: Location");
            builder.AppendLine("    [Extension]");
            builder.AppendLine($"    static func Report{diagnostic.Identifier}({string.Join(", ", parameters)}) {{");
            builder.Append($"        diagnostics.Report(Diagnostic.Create(CompilerDiagnostics.{diagnostic.Identifier}, location");
            foreach (var argument in diagnostic.Arguments)
                builder.Append($", @{argument}");
            builder.AppendLine("))");
            builder.AppendLine("    }");
            builder.AppendLine();
        }
        builder.AppendLine("}");
        return builder.ToString();
    }
}
